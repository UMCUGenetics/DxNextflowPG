def main():
    import argparse

    # Parse command line arguments
    parser = argparse.ArgumentParser(
        description='Clean and format Excel data, and store dbsnp IDstar alleles')

    parser.add_argument(
        '--translation_table',
        dest='excel_path',
        type=str,
        help='Path to the Excel file')

    parser.add_argument(
        "--dbSNP",
        dest='db_snp',
        type=str,
        help='Path to (subsetted) dbSNP vcf')

    parser.add_argument(
        "--vcf",
        dest='vcf_path',
        type=str,
        help="Path to the folder containing the vcf/called zip files")

    parser.add_argument(
        "-o",
        dest="outfile",
        type=str,
        help="Path to the output in csv format"
    )
    args = parser.parse_args()

    # Clean the data
    logging.info("Cleaning up excel conversion table")
    excel_conversions = databases.import_clean_excel(args.excel_path)

    logging.info("Importing dbSNP subset")

    # Dict to map genomic positions to dbSNP rs ids
    rs_db = databases.import_dbsnp(args.db_snp)

    logging.info("Importing sample VCF files")
    sample = Sample(args.vcf_path, rs_db)

    with open(args.outfile, 'w') as output_file:

        header = ["Sample", "Gene", "Excel_Genotype"]#, "PyPGx_Genotype"]
        print("\t".join(header))



        pgx_gene = sample.pg_gene
        data_subset = excel_conversions[excel_conversions['gene'] == pgx_gene]
        pgx_genotypes = list(set(data_subset['genotype_autogenerated_name']))

        genotyped_excel = False
        excel_genotype = None

        for pgx_genotype in pgx_genotypes:
            data_subset_genotype = data_subset[
                data_subset['genotype_autogenerated_name'] == pgx_genotype]
            c_genotype = databases.Genotype(pgx_gene, data_subset_genotype)
            c_genotype.add_variants(
                zip(data_subset_genotype['variant_id'], data_subset_genotype['variant_result']))

           

            lookup = [str(variant) in sample.rs_gt for variant in c_genotype.variants]

                
            if False in lookup:
                # logging.debug(f"Sample {sample.vcf} is not {pgx_genotype}")
                pass
            else:
                # logging.info(f" FOUND Sample {samples.vcf} is {pgx_genotype}")
                genotyped_excel = True
                excel_genotype = pgx_genotype
                logger.debug([str(variant) for variant in c_genotype.variants])


        if not genotyped_excel:
            excel_genotype = 'Undetermined'


        outline = [sample.name,pgx_gene, excel_genotype]#, sample.get_pypgx_star_allele()]
        print("\t".join(outline))
        
    
if __name__ == '__main__':
    main()
